import pandas as pd

# -----------------------------
# 파일 경로 지정
# -----------------------------
# 원본 CSV 파일 경로를 지정합니다.
# (환경에 따라 파일명이 다를 수 있으니 필요하면 수정하세요)
file_path = "방위사업청_국내조달 경쟁 입찰결과_(2024년)-1.csv"

# -----------------------------
# CSV 읽기 (인코딩 예외 처리)
# -----------------------------
# 판다스의 read_csv는 기본적으로 UTF-8을 가정하지만,
# 국내 공공데이터는 CP949 (또는 EUC-KR)로 인코딩된 경우가 많아 먼저 CP949로 시도합니다.
# low_memory=False는 큰 파일을 읽을 때 타입 추론 오류를 방지하기 위해 사용합니다.
try:
    # 첫 시도: CP949 (Windows 한국어)로 읽기
    df = pd.read_csv(file_path, encoding="cp949", low_memory=False)
except Exception:
    # 실패 시: UTF-8 with BOM (utf-8-sig)로 다시 시도
    # (utf-8-sig는 파일에 BOM(Byte Order Mark)이 있을 때 안전)
    df = pd.read_csv(file_path, encoding="utf-8-sig", low_memory=False)

# -----------------------------
# 분석에서 사용할 컬럼 목록 정의
# -----------------------------
# 원본 파일에서 관심 있는 컬럼들을 미리 정의합니다.
# 실제 파일에 컬럼이 없을 수 있으므로 이후에 존재 여부를 체크합니다.
target_columns = [
    "입찰공고명",            # 공고 제목 (연구/개발 여부 판단용)
    "공고기관명",            # 공고를 낸 기관 이름(준식별자)
    "기초금액",              # 공고에 제시된 기초금액 (금액형)
    "개찰일자",              # 개찰(입찰 열람) 날짜 (날짜형)
    "최종낙찰금액",          # 실제 낙찰된 금액 (금액형, 민감한 정보 가능)
    "최종낙찰율",            # 낙찰율(비율)
    "최종낙찰일자",          # 낙찰 일자 (날짜형)
    "최종낙찰업체명",        # 낙찰 업체명 (준식별자 / 민감한 정보 가능)
    "최종낙찰업체대표자명",  # 업체 대표자명 (개인 식별 가능성 있음)
    "최종낙찰업체담당자명",  # 업체 담당자명
    "최종낙찰업체주소"       # 업체 주소 (개인/기관 식별에 민감도가 높을 수 있음)
]

# -----------------------------
# 실제로 파일에 존재하는 컬럼 필터링
# -----------------------------
# 정의한 target_columns 중 실제로 DF에 존재하는 컬럼만 사용합니다.
# (파일의 컬럼명이 일부 다르면 KeyError 방지 및 유연성 확보)
existing_cols = [c for c in target_columns if c in df.columns]

# -----------------------------
# 연구개발 관련 키워드 정의 및 필터링 패턴 생성
# -----------------------------
# '입찰공고명'에 연구개발 관련 키워드(예: 연구, 개발 등)가 포함된 레코드를 추출하기 위한 키워드 목록.
# 필요시 여기에 더 많은 키워드를 추가하세요.
keywords = ["연구", "개발", "R&D", "시험", "분석", "설계", "시제품", "모델", "시뮬레이션"]

# 정규표현식 OR(|) 연산자를 이용해 하나의 패턴 문자열로 결합합니다.
# str.contains에서는 이 패턴을 그대로 사용합니다.
pattern = "|".join(keywords)

# -----------------------------
# 연구개발 관련 레코드 필터링 수행
# -----------------------------
# '입찰공고명' 컬럼이 존재하는 경우에 한해 필터링을 수행합니다.
# - .astype(str) : NaN을 포함해 문자열 연산에서 오류 방지
# - .str.contains(pattern, case=False, na=False) :
#     case=False -> 대소문자 무시(R&D 등)
#     na=False   -> NaN 값은 False로 처리(즉 필터에서 제외)
if "입찰공고명" in df.columns:
    # 키워드 패턴이 포함된 행만 선별
    rd_df = df[df["입찰공고명"].astype(str).str.contains(pattern, case=False, na=False)]

    # 결과에서 기존에 존재하는 target 컬럼들만 선택하여 표시(일부 컬럼이 없을 수 있으므로 안전하게 처리)
    # head(30)은 상위 30개만 미리 확인용으로 출력하도록 함 (원하면 제거)
    rd_result = rd_df[existing_cols].head(30)  # 상위 30개 미리보기
else:
    # 만약 '입찰공고명' 컬럼 자체가 없으면 오류 안내용 DataFrame을 반환
    rd_result = pd.DataFrame({"오류": ["'입찰공고명' 열이 존재하지 않습니다."]})

# -----------------------------
# 최종 결과 출력
# -----------------------------
# rd_result에는 연구개발 관련 상위 30개 레코드(또는 오류 메시지)가 들어있습니다.
# 필요시 아래를 주석 해제하여 CSV로 저장할 수 있습니다.
#
# 출력 예:
# print(rd_result)
#
# 저장 예:
# rd_result.to_csv("RnD_filtered_preview.csv", index=False, encoding="utf-8-sig")
#
rd_result
