# ============================================================
# [코드 개요]
# 본 스크립트는 '방위사업청 국내조달 경쟁 입찰결과' 원본 데이터(Raw Data)로부터
# 본 연구의 실험 목적에 부합하는 '연구개발(R&D)' 관련 데이터를 선별하고,
# 개인정보 및 민감정보가 포함된 핵심 속성(Column)을 추출하기 위해 작성되었다.
#
# [주요 기능]
# 1. 대용량 공공데이터 로드 및 인코딩 호환성 처리 (CP949/UTF-8-SIG)
# 2. 분석 대상 속성(Target Features) 정의 및 유효성 검증
# 3. 정규표현식(Regular Expression)을 활용한 R&D 관련 키워드 필터링
# ============================================================

import pandas as pd

# -----------------------------------------------------------------------------
# 1. 데이터 파일 경로 설정 및 로드 (Data Loading)
# -----------------------------------------------------------------------------
# 분석 대상 원본 데이터 파일의 경로를 지정한다.
# 본 연구에서는 2016-2024년 방위사업청 조달 데이터 일부를 예시로 사용한다.
file_path = "방위사업청_국내조달 경쟁 입찰결과_-1.csv"

# [인코딩 처리 로직]
# 국내 공공데이터 포털(data.go.kr)에서 제공하는 CSV 파일은 통상적으로
# 'CP949' (Windows 한글 확장 완성형) 인코딩을 사용하나, 경우에 따라
# 'UTF-8' 또는 'UTF-8-SIG' 형식을 따르기도 한다.
# 데이터 로드 시 인코딩 불일치로 인한 오류(UnicodeDecodeError)를 방지하기 위해
# 예외 처리(Try-Except) 구문을 사용하여 호환성을 확보한다.

try:
    # 1차 시도: 국내 환경 표준인 CP949로 읽기 시도
    # low_memory=False: 대용량 데이터 처리 시 컬럼의 데이터 타입(Dtype) 추론 오류 방지
    df = pd.read_csv(file_path, encoding="cp949", low_memory=False)
    print(f"[System] 데이터 로드 성공 (Encoding: CP949)")

except Exception:
    # 1차 실패 시: UTF-8-SIG(BOM 포함)로 재시도
    # UTF-8-SIG는 엑셀(Excel)에서 저장된 CSV 파일의 호환성을 보장함
    df = pd.read_csv(file_path, encoding="utf-8-sig", low_memory=False)
    print(f"[System] 데이터 로드 성공 (Encoding: UTF-8-SIG)")

# -----------------------------------------------------------------------------
# 2. 분석 대상 변수(Feature Selection) 정의
# -----------------------------------------------------------------------------
# 전체 데이터 속성 중, 본 연구의 실험(재현 데이터 생성 및 위험도 분석)에 필요한
# 핵심 변수와 식별자(Identifier), 준식별자(Quasi-Identifier)를 정의한다.
target_columns = [
    "입찰공고명",            # [Text] 연구개발 여부를 판단하는 핵심 텍스트 데이터
    "공고기관명",            # [Categorical] 발주 기관 (준식별자)
    "기초금액",              # [Numerical] 사업 규모를 나타내는 연속형 변수
    "개찰일자",              # [Date] 시계열 분석을 위한 날짜 정보
    "최종낙찰금액",          # [Numerical] 재현 대상 핵심 민감 정보 (Target)
    "최종낙찰율",            # [Numerical] 낙찰 금액의 비율 정보
    "최종낙찰일자",          # [Date] 계약 확정 일자
    "최종낙찰업체명",        # [Categorical] 수주 업체 정보 (직접 식별자 성격)
    "최종낙찰업체대표자명",  # [Sensitive] 개인정보 (비식별화 필수 대상)
    "최종낙찰업체담당자명",  # [Sensitive] 개인정보 (비식별화 필수 대상)
    "최종낙찰업체주소"       # [Categorical/Text] 위치 정보 (준식별자)
]

# [유효성 검증]
# 정의된 컬럼이 실제 로드된 데이터프레임(df)에 존재하는지 확인한다.
# 이는 데이터 버전 변경 등으로 인한 'KeyError' 발생을 방지하기 위함이다.
existing_cols = [c for c in target_columns if c in df.columns]

# -----------------------------------------------------------------------------
# 3. 연구개발(R&D) 관련 레코드 필터링 (Keyword Filtering)
# -----------------------------------------------------------------------------
# 방산 데이터 중 일반 물품 구매(소모품 등)를 제외하고, 보안 민감도가 높은
# '무기체계 연구개발' 및 '핵심 기술' 관련 사업만을 추출한다.

# 3-1. 필터링 키워드 정의
# 국방 R&D 사업의 특성을 반영한 핵심 키워드 리스트
keywords = [
    "연구", "개발", "R&D",    # R&D 직접 관련 용어
    "시험", "분석", "설계",   # 기술 용역 관련 용어
    "시제품", "모델",         # 프로토타입 개발 관련 용어
    "시뮬레이션"              # M&S(Modeling & Simulation) 관련 용어
]

# 3-2. 정규표현식 패턴 생성
# 여러 키워드 중 하나라도 포함되면 추출하기 위해 OR 연산자(|)로 결합한다.
pattern = "|".join(keywords)

# 3-3. 조건부 데이터 추출 실행
if "입찰공고명" in df.columns:
    # str.contains(): 정규표현식을 사용하여 문자열 매칭 수행
    # - case=False: 영문 대소문자 구분 없음 (R&D, r&d 모두 탐지)
    # - na=False: 결측값(NaN)은 필터링 대상에서 제외
    rd_df = df[df["입찰공고명"].astype(str).str.contains(pattern, case=False, na=False)]

    # 선택된 컬럼만 추출하여 최종 결과셋 생성
    # (head(30)은 검증용으로 상위 30개만 추출, 전체 저장 시 제거 가능)
    rd_result = rd_df[existing_cols].head(30)
    
    print(f"[System] 필터링 완료. 추출된 R&D 관련 데이터 수: {len(rd_df)}건")

else:
    # 예외 처리: 필터링 기준 컬럼이 없는 경우
    rd_result = pd.DataFrame({"Error": ["데이터셋에 '입찰공고명' 컬럼이 존재하지 않습니다."]})
    print("[Error] 필터링 기준 컬럼 부재")
